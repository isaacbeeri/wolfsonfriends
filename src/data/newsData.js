const STORAGE_KEY = "fwmc_news_items_v2";
const LEGACY_STORAGE_KEY = "fwmc_news_items_v1";

// IndexedDB configuration for fail-safe large storage
const IDB_NAME = "fwmc_cms_db";
const IDB_STORE = "news_store";
const IDB_KEY = "active_news_items";

function openIndexedDB() {
  return new Promise((resolve, reject) => {
    if (typeof window === "undefined" || !window.indexedDB) {
      return reject(new Error("IndexedDB not available"));
    }
    const request = indexedDB.open(IDB_NAME, 1);
    request.onupgradeneeded = (e) => {
      const db = e.target.result;
      if (!db.objectStoreNames.contains(IDB_STORE)) {
        db.createObjectStore(IDB_STORE);
      }
    };
    request.onsuccess = () => resolve(request.result);
    request.onerror = () => reject(request.error);
  });
}

export async function saveToIndexedDB(items) {
  try {
    const db = await openIndexedDB();
    const tx = db.transaction(IDB_STORE, "readwrite");
    tx.objectStore(IDB_STORE).put(items, IDB_KEY);
    return new Promise((resolve) => {
      tx.oncomplete = () => resolve(true);
      tx.onerror = () => resolve(false);
    });
  } catch (err) {
    console.warn("IndexedDB save error:", err);
    return false;
  }
}

export async function loadFromIndexedDB() {
  try {
    const db = await openIndexedDB();
    const tx = db.transaction(IDB_STORE, "readonly");
    const req = tx.objectStore(IDB_STORE).get(IDB_KEY);
    return new Promise((resolve) => {
      req.onsuccess = () => {
        if (Array.isArray(req.result) && req.result.length > 0) {
          resolve(req.result);
        } else {
          resolve(null);
        }
      };
      req.onerror = () => resolve(null);
    });
  } catch (err) {
    return null;
  }
}

// Client-side image compression utility
export function compressImageFile(file, maxWidth = 800, maxHeight = 800, quality = 0.78) {
  return new Promise((resolve, reject) => {
    if (!file) return reject(new Error("No file provided"));

    // If SVG or tiny file, read as is
    if (file.type === "image/svg+xml" || file.size < 45000) {
      const reader = new FileReader();
      reader.onload = (e) => resolve(e.target.result);
      reader.onerror = reject;
      reader.readAsDataURL(file);
      return;
    }

    const reader = new FileReader();
    reader.onload = (e) => {
      const img = new Image();
      img.onload = () => {
        let width = img.width;
        let height = img.height;

        if (width > maxWidth || height > maxHeight) {
          if (width / height > maxWidth / maxHeight) {
            height = Math.round((height * maxWidth) / width);
            width = maxWidth;
          } else {
            width = Math.round((width * maxHeight) / height);
            height = maxHeight;
          }
        }

        const canvas = document.createElement("canvas");
        canvas.width = width;
        canvas.height = height;
        const ctx = canvas.getContext("2d");
        ctx.imageSmoothingEnabled = true;
        ctx.imageSmoothingQuality = "high";
        ctx.drawImage(img, 0, 0, width, height);

        const compressedDataUrl = canvas.toDataURL("image/jpeg", quality);
        resolve(compressedDataUrl);
      };
      img.onerror = () => resolve(e.target.result);
      img.src = e.target.result;
    };
    reader.onerror = reject;
    reader.readAsDataURL(file);
  });
}

// Sanitize and ensure uniform object format
export function sanitizeNewsItems(items) {
  if (!Array.isArray(items)) return defaultNewsItems;
  return items.map(item => {
    const formatLocalized = (field, fallback = "") => {
      if (!field) return { he: fallback, en: fallback, fr: fallback, de: fallback };
      if (typeof field === "string") return { he: field, en: field, fr: field, de: field };
      return {
        he: field.he || fallback,
        en: field.en || field.he || fallback,
        fr: field.fr || field.en || field.he || fallback,
        de: field.de || field.en || field.he || fallback
      };
    };

    return {
      id: item.id || `news-${Date.now()}-${Math.random().toString(36).substr(2, 5)}`,
      active: item.active !== false,
      category: formatLocalized(item.category, "חדשות"),
      date: formatLocalized(item.date, "2026"),
      title: formatLocalized(item.title, "עדכון"),
      snippet: formatLocalized(item.snippet, ""),
      image: item.image || "/images/hero-aerial.jpg",
      link: item.link || "#projects",
      linkText: formatLocalized(item.linkText, "לפרטים נוספים")
    };
  });
}

// In-memory cache to guarantee instantaneous UI updates
let cachedNewsItems = null;

export function getStoredNews() {
  if (typeof window === "undefined") return defaultNewsItems;
  if (cachedNewsItems && cachedNewsItems.length > 0) return cachedNewsItems;

  let loaded = null;

  // Try reading from new storage key
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        loaded = sanitizeNewsItems(parsed);
      }
    }
  } catch (err) {
    console.warn("LocalStorage v2 read error:", err);
  }

  // Fallback to legacy storage key
  if (!loaded) {
    try {
      const legacySaved = localStorage.getItem(LEGACY_STORAGE_KEY);
      if (legacySaved) {
        const parsedLegacy = JSON.parse(legacySaved);
        if (Array.isArray(parsedLegacy) && parsedLegacy.length > 0) {
          loaded = sanitizeNewsItems(parsedLegacy);
          // Migrate to v2
          localStorage.setItem(STORAGE_KEY, JSON.stringify(loaded));
        }
      }
    } catch (err) {
      console.warn("Legacy localStorage read error:", err);
    }
  }

  const result = loaded || defaultNewsItems;
  cachedNewsItems = result;

  // Background check IndexedDB for any richer/larger dataset
  if (typeof window !== "undefined" && window.indexedDB) {
    loadFromIndexedDB().then(idbItems => {
      if (idbItems && Array.isArray(idbItems) && idbItems.length >= result.length) {
        const sanitized = sanitizeNewsItems(idbItems);
        cachedNewsItems = sanitized;
        try {
          localStorage.setItem(STORAGE_KEY, JSON.stringify(sanitized));
        } catch (e) {}
        window.dispatchEvent(new CustomEvent("fwmc_news_updated", { detail: sanitized }));
      }
    }).catch(() => {});
  }

  return result;
}

export function saveStoredNews(items) {
  if (typeof window === "undefined") return;

  const sanitized = sanitizeNewsItems(items);
  cachedNewsItems = sanitized;

  // 1. ALWAYS dispatch event FIRST so the UI and roller frame update immediately without waiting!
  try {
    window.dispatchEvent(new CustomEvent("fwmc_news_updated", { detail: sanitized }));
  } catch (err) {
    console.error("Failed to dispatch news update event:", err);
  }

  // 2. Persist to IndexedDB (virtually unlimited quota!)
  saveToIndexedDB(sanitized);

  // 3. Persist to localStorage
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(sanitized));
  } catch (err) {
    console.warn("LocalStorage quota hit, storing optimized version...", err);
    try {
      // If quota exceeded, compress images further for localStorage (IDB retains full quality)
      const slim = sanitized.map(item => {
        if (item.image && item.image.startsWith("data:") && item.image.length > 80000) {
          return { ...item, image: "/images/hero-aerial.jpg" };
        }
        return item;
      });
      localStorage.setItem(STORAGE_KEY, JSON.stringify(slim));
    } catch (err2) {
      console.error("Critical localStorage quota exceeded:", err2);
    }
  }
}

export function resetStoredNews() {
  cachedNewsItems = defaultNewsItems;
  if (typeof window !== "undefined") {
    try {
      localStorage.removeItem(STORAGE_KEY);
      localStorage.removeItem(LEGACY_STORAGE_KEY);
    } catch (err) {}
    saveToIndexedDB(defaultNewsItems);
    window.dispatchEvent(new CustomEvent("fwmc_news_updated", { detail: defaultNewsItems }));
  }
  return defaultNewsItems;
}
